#!/usr/bin/env python3
"""Make the flipbook data from the built handout: small thumbnails of every page preview
(images/page-thumbs/) and flipbook/pages.js (page number, title, group) read from the page
footers in source/index.html. Run after build_pdf.sh (build_pdf.sh does)."""
import re, json, html
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parent.parent
s = (root / 'source/index.html').read_text()
titles = [html.unescape(t) for t in re.findall(r'<div class="foot"><span>(.*?)</span><span>Page \d+ of \d+</span></div>', s)]
prev = sorted((root / 'images/page-previews').glob('page-*.png'))
assert len(prev) == len(titles), (len(prev), len(titles))
(root / 'images/page-thumbs').mkdir(exist_ok=True)
for old in (root / 'images/page-thumbs').glob('page-*'):
    old.unlink()
pages = []
part2 = next(i for i, t in enumerate(titles, 1) if t.startswith('Know Your Mixer'))
for i, (t, p) in enumerate(zip(titles, prev), 1):
    im = Image.open(p).convert('RGB')
    im.thumbnail((240, 320), Image.LANCZOS)
    im.save(root / f'images/page-thumbs/page-{i:02d}.jpg', quality=85, optimize=True)
    if i == 1: t, g = 'Cover', 'Start'
    elif i == 2: g = 'Start'
    elif i < part2: g = 'Part 1 - Set it up'
    elif t.startswith(('No-sound', 'Quick')): g = 'Help and reference'
    else: g = 'Part 2 - Know Your Mixer'
    pages.append({'n': i, 'title': t, 'group': g, 'img': p.name})
(root / 'flipbook').mkdir(exist_ok=True)
(root / 'flipbook/pages.js').write_text('// generated by tools/make_flipbook.py - do not edit\nwindow.SOP_PAGES = ' + json.dumps(pages, indent=1) + ';\n')
print('flipbook pages:', len(pages))

# --- GitHub page-by-page viewer: flipbook/pages/page-NN.md, each with big prev / next arrows.
# Works on github.com with no GitHub Pages (plain markdown + images).
N = len(pages)
pd = root / 'flipbook/pages'
pd.mkdir(exist_ok=True)
for old in pd.glob('page-*.md'):
    old.unlink()
def arrow(side, n):
    if 1 <= n <= N:
        t = pages[n-1]['title'].replace('"', "'")
        return f'<a href="page-{n:02d}.md" title="{"Previous" if side == "left" else "Next"}: page {n} - {t}"><img src="../../images/ui/arrow-{side}-on.svg" width="84" alt="{"Previous" if side == "left" else "Next"} page"></a>'
    return f'<img src="../../images/ui/arrow-{side}-off.svg" width="84" alt="">'
for p in pages:
    n = p['n']
    prv = f'<a href="page-{n-1:02d}.md">⬅️ {n-1} · {pages[n-2]["title"]}</a>' if n > 1 else '⬅️ (this is the first page)'
    nxt = f'<a href="page-{n+1:02d}.md">{pages[n]["title"]} · {n+1} ➡️</a>' if n < N else '(this is the last page) <a href="../../README.md">🏠 back to the start</a>'
    (pd / f'page-{n:02d}.md').write_text(f'''<!-- generated by tools/make_flipbook.py - do not edit -->
<p align="center"><a href="../../README.md">🏠 Home</a> &nbsp;·&nbsp; <a href="page-01.md">Cover</a> &nbsp;·&nbsp; <a href="page-02.md">Contents</a> &nbsp;·&nbsp; <a href="../../handout/voicemeeter-potato-sop.pdf">⬇️ PDF</a></p>

<h3 align="center">Page {n} of {N} · {p["title"]}</h3>

<table align="center"><tr>
<td valign="middle" align="center">{arrow("left", n-1)}</td>
<td align="center"><a href="../../images/page-previews/{p["img"]}"><img src="../../images/page-previews/{p["img"]}" width="600" alt="Page {n}: {p["title"]}"></a></td>
<td valign="middle" align="center">{arrow("right", n+1)}</td>
</tr></table>

<p align="center">{prv} &nbsp;&nbsp;|&nbsp;&nbsp; {nxt}</p>
<p align="center"><sub>Click the big arrows to turn the page. Click the page to see it full size.</sub></p>
''')
print('page viewer files:', N)
